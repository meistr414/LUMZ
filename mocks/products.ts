function buildColours(slug: string, name: string, keys: ColourKey[]): Colour[] {
  return keys.map((key) => ({
    id: key,
    name: COLOUR_SWATCHES[key].name,
    hex: COLOUR_SWATCHES[key].hex,
    images: colourImages(slug, key, name),
  }));
}

function buildVariants(options: {
  slug: string;
  colours: ColourKey[];
  sizes: string[];
  priceCents: number;
  compareAtCents?: number;
  stock?: (colour: ColourKey, size: string) => number;
}): Variant[] {
  const { slug, colours, sizes, priceCents, compareAtCents, stock } = options;
  const variants: Variant[] = [];
  for (const colour of colours) {
    for (const size of sizes) {
      variants.push({
        id: `${slug}-${colour}-${size}`.toLowerCase(),
        sku: `${slug}-${colour}-${size}`.toUpperCase(),
        colourId: colour,
        size,
        priceCents,
        compareAtCents,
        stock: stock ? stock(colour, size) : 15,
      });
    }
  }
  return variants;
}

